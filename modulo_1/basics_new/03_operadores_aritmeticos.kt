fun main() {
    val numero1 = 10
    val numero2 = 2
        
    // Suma
    println("$numero1 + $numero2 = ${numero1 + numero2}")
    
    // Resta
    println("$numero1 - $numero2 = ${numero1 - numero2}")
    
    // Multiplicación
    println("$numero1 * $numero2 = ${numero1 * numero2}")
    
    // División
    println("$numero1 / $numero2 = ${numero1 / numero2}")
}
