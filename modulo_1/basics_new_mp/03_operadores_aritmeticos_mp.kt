// --- Operadores aritmeticos

fun main() {
    val costoConsulta = 80.0
    val descuento = 20.0

    // Suma
    println("$costoConsulta + $descuento = ${costoConsulta + descuento}")

    // Resta
    println("$costoConsulta - $descuento = ${costoConsulta - descuento}")

    // Multiplicacion
    println("$costoConsulta * 2 = ${costoConsulta * 2}")

    // Division
    println("$costoConsulta / 2 = ${costoConsulta / 2}")

    val totalPacientes = 10
    val consultasPorDia = 3

    println("$totalPacientes + $consultasPorDia = ${totalPacientes + consultasPorDia}")
    println("$totalPacientes - $consultasPorDia = ${totalPacientes - consultasPorDia}")
    println("$totalPacientes * $consultasPorDia = ${totalPacientes * consultasPorDia}")
    println("$totalPacientes / $consultasPorDia = ${totalPacientes / consultasPorDia}")
}
